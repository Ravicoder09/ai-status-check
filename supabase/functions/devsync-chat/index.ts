import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages, type, code, language, question } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    let aiMessages: Array<{role: string, content: string}> = [];

    const systemPrompt = `You are DevAssistant AI, a professional coding assistant embedded in DevSync AI - a collaborative coding environment.

You help developers with:
- Debugging code issues
- Code explanation and walkthroughs
- Performance optimization
- Best practices and design patterns
- Architecture design decisions

Guidelines:
- Give clear, direct, professional answers
- Use markdown formatting for readability
- Include code examples when relevant using fenced code blocks with language tags
- Be concise but thorough
- When analyzing code, point out potential issues and suggest improvements`;

    if (type === "code-assist" && code) {
      aiMessages = [
        { role: "system", content: systemPrompt },
        { role: "user", content: `Analyze this ${language || 'javascript'} code and answer the question:\n\nCode:\n\`\`\`${language || 'javascript'}\n${code}\n\`\`\`\n\nQuestion: ${question}` },
      ];
    } else {
      aiMessages = [
        { role: "system", content: systemPrompt },
        ...(messages || []),
      ];
    }

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: aiMessages,
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add credits to continue." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
